const {
    LISTING_STATUS
} = require('./listing-state');

const ALLOWED_TRANSITIONS = {

    [LISTING_STATUS.DRAFT]: [
        LISTING_STATUS.ACTIVE,
        LISTING_STATUS.CANCELLED
    ],

    [LISTING_STATUS.ACTIVE]: [
        LISTING_STATUS.PAUSED,
        LISTING_STATUS.RESERVED,
        LISTING_STATUS.PAYMENT_PENDING,
        LISTING_STATUS.CANCELLED,
        LISTING_STATUS.EXPIRED
    ],

    [LISTING_STATUS.PAUSED]: [
        LISTING_STATUS.ACTIVE,
        LISTING_STATUS.CANCELLED
    ],

    [LISTING_STATUS.RESERVED]: [
        LISTING_STATUS.ACTIVE,
        LISTING_STATUS.PAYMENT_PENDING,
        LISTING_STATUS.CANCELLED
    ],

    [LISTING_STATUS.PAYMENT_PENDING]: [
        LISTING_STATUS.PAYMENT_SUCCESS,
        LISTING_STATUS.PAYMENT_FAILED
    ],

    [LISTING_STATUS.PAYMENT_SUCCESS]: [
        LISTING_STATUS.TRANSFER_PENDING
    ],

    [LISTING_STATUS.PAYMENT_FAILED]: [
        LISTING_STATUS.ACTIVE
    ],

    [LISTING_STATUS.TRANSFER_PENDING]: [
        LISTING_STATUS.GYM_APPROVAL_PENDING,
        LISTING_STATUS.TRANSFER_REJECTED
    ],

    [LISTING_STATUS.GYM_APPROVAL_PENDING]: [
        LISTING_STATUS.SOLD,
        LISTING_STATUS.TRANSFER_REJECTED
    ],

    [LISTING_STATUS.TRANSFER_REJECTED]: [
        LISTING_STATUS.ACTIVE
    ],

    [LISTING_STATUS.EXPIRED]: [
        LISTING_STATUS.ACTIVE,
        LISTING_STATUS.CANCELLED
    ],

    [LISTING_STATUS.SOLD]: [],

    [LISTING_STATUS.CANCELLED]: [
        LISTING_STATUS.ACTIVE
    ]

};

const canTransition = (
    currentStatus,
    nextStatus
) => {

    return (
        ALLOWED_TRANSITIONS[currentStatus] || []
    ).includes(nextStatus);

};

module.exports = {

    ALLOWED_TRANSITIONS,

    canTransition

};